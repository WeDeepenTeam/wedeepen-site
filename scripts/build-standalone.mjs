// Minimal Markdown for llms.txt: ## headings, > lead, - lists, [text](url), **bold**.
function inline(s) {
  return esc(s)
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, (_, t, u) => `<a href="${u.replace(/^https:\/\/wedeepen\.com(?=\/)/, '')}">${t}</a>`)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[\s(])(https:\/\/wedeepen\.com(\/[A-Za-z0-9\/_.-]*)?)/g, (_, pre, u, p) => `${pre}<a href="${p || '/'}">${u}</a>`);
}
function markdown(md) {
  const out = [];
  let list = null;
  let para = [];
  const flushPara = () => { if (para.length) { out.push(`<p>${inline(para.join(' '))}</p>`); para = []; } };
  const flushList = () => { if (list) { out.push(`<ul>\n${list.map((li) => `  <li>${inline(li)}</li>`).join('\n')}\n</ul>`); list = null; } };
  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    if (/^#\s/.test(line)) continue; // the template owns the H1
    if (/^##\s/.test(line)) { flushPara(); flushList(); out.push(`<h2>${inline(line.replace(/^##\s+/, ''))}</h2>`); continue; }
    if (/^>\s?/.test(line)) { flushPara(); flushList(); out.push(`<p class="text-lg">${inline(line.replace(/^>\s?/, ''))}</p>`); continue; }
    if (/^-\s+/.test(line)) { flushPara(); (list ||= []).push(line.replace(/^-\s+/, '')); continue; }
    if (!line.trim()) { flushPara(); flushList(); continue; }
    if (list) { list[list.length - 1] += ` ${line.trim()}`; continue; }
    para.push(line.trim());
  }
  flushPara(); flushList();
  return out.join('\n');
}

async function buildFacts(sec) {
  const shell = borrowShell(donor, sec.path);
  const meta = await readJson(sec.data);
  const md = await fs.readFile(path.join(ROOT, sec.source), 'utf8');
  const url = `${SITE}${sec.path}`;
  const org = await ldNode('index.html', ORG_ID);
  const person = await ldNode('about/index.html', PERSON_ID);
  const membership = await ldNode('index.html', `${SITE}/#membership`);
  const jsonLd = {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'AboutPage',
        '@id': `${url}#webpage`,
        url,
        name: meta.title,
        description: meta.description,
        dateModified: meta.verified,
        isPartOf: { '@id': `${SITE}/#website` },
        about: { '@id': ORG_ID },
        mainEntity: { '@id': ORG_ID },
      },
      org,
      person,
      membership,
    ],
  };
  const body = `  <!-- ============================
       STANDALONE: FACTS (generated by scripts/build-standalone.mjs from ${sec.source}; edit that file)
       ============================ -->
  <main>
  <section class="pt-32 md:pt-40 pb-8 px-6">
    <div class="max-w-3xl mx-auto">
      <p class="text-gold text-xs tracking-[0.25em] uppercase font-semibold mb-3">Fact sheet</p>
      <h1 class="font-heading text-4xl md:text-5xl font-normal leading-[1.1] tracking-tight">${esc(meta.heading || meta.title)}</h1>
      <p class="text-white/50 text-sm mt-5">Verified <time datetime="${esc(meta.verified)}">${esc(prettyDate(meta.verified))}</time> &middot; For journalists, partners, and AI assistants. Plain-text version: <a href="/llms.txt" class="text-gold hover:underline">llms.txt</a></p>
    </div>
  </section>
  <section class="pb-20 md:pb-28 px-4 sm:px-6">
    <div class="max-w-3xl mx-auto bg-white rounded-2xl px-5 py-8 sm:px-10 sm:py-12">
      <article class="prose prose-gray prose-a:text-[#A01B4A] max-w-none">
${hardenLinks(markdown(md))}
      </article>
    </div>
  </section>
  </main>`;
  await fs.mkdir(dirOf(sec.path), { recursive: true });
  await fs.writeFile(path.join(dirOf(sec.path), 'index.html'),
    page(shell, { title: meta.title, description: meta.description, url, image: meta.image || null, type: 'website' }, [jsonLd], body), 'utf8');
  console.log(`Wrote ${sec.path} from ${sec.source}`);
  return [{ loc: url, lastmod: meta.verified, changefreq: 'monthly', priority: '0.8' }];
}

// --- main -------------------------------------------------------------------------

let xml = await fs.readFile(SITEMAP, 'utf8');
const before = xml;
for (const sec of sections) {
  const entries = sec.kind === 'collection' ? await buildCollection(sec)
    : sec.kind === 'facts' ? await buildFacts(sec)
      : (() => { throw new Error(`build-standalone: unknown kind ${sec.kind}`); })();
  xml = sitemapWithSection(xml, sec.path, entries);
}
if (xml !== before) await fs.writeFile(SITEMAP, xml, 'utf8');
