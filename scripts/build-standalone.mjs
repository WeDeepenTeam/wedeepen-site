#!/usr/bin/env node
/**
 * build-standalone.mjs — generate the standalone sections listed in
 * scripts/standalone/sections.json.
 *
 * Standalone sections follow the /blog/ pattern on purpose:
 *   - generated from committed data files (never hand-edit the HTML),
 *   - carry the normal site header and footer, so they link OUT to the site,
 *   - are NOT in the nav and are never linked FROM main-site pages
 *     (scripts/standalone/check-isolation.mjs enforces this),
 *   - are discoverable by crawlers and AI tools through sitemap.xml,
 *     llms.txt, llms-full.txt and IndexNow.
 *
 * Kinds:
 *   collection  /<path>/ index + /<path>/<slug>/ pages from a JSON data file
 *               (answer-first pages: short answer, body, FAQ, sources)
 *   facts       a single /<path>/ page rendered from llms.txt, so the
 *               human-readable fact sheet can never disagree with it
 *
 * Run: node scripts/build-standalone.mjs     (npm run standalone:build)
 * In CI: .github/workflows/standalone-build.yml on pushes to the data files.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE, esc, safeSlug, prettyDate, faqFromHtml, borrowShell, page, sitemapWithSection } from './standalone/shell.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DONOR = path.join(ROOT, 'podcast/index.html');
const SITEMAP = path.join(ROOT, 'sitemap.xml');
const { sections } = JSON.parse(await fs.readFile(path.join(ROOT, 'scripts/standalone/sections.json'), 'utf8'));
const donor = await fs.readFile(DONOR, 'utf8');

const readJson = async (rel) => JSON.parse(await fs.readFile(path.join(ROOT, rel), 'utf8'));
const dirOf = (urlPath) => path.join(ROOT, urlPath.replace(/^\/|\/$/g, ''));
const day = (iso) => String(iso || '').slice(0, 10);

// Pull a JSON-LD node (by @id) out of a committed page, so the standalone
// pages describe WeDeepen and Christina with exactly the same data.
async function ldNode(file, id) {
  const html = await fs.readFile(path.join(ROOT, file), 'utf8');
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    let d; try { d = JSON.parse(m[1]); } catch { continue; }
    for (const n of (d['@graph'] || [d])) if (n['@id'] === id) return n;
  }
  throw new Error(`build-standalone: no JSON-LD node ${id} in ${file}`);
}
const ORG_ID = `${SITE}/#organization`;
const PERSON_ID = `${SITE}/about/#christina-weber`;

// External links open safely and are marked as such.
const hardenLinks = (html) => html.replace(/<a\b([^>]*?)href="(https?:\/\/(?!(?:www\.)?wedeepen\.com|circle\.wedeepen\.com)[^"]+)"([^>]*)>/gi,
  (m, a, href, b) => (/\brel=/.test(a + b) ? m : `<a${a}href="${href}"${b} rel="noopener" target="_blank">`));

// --- collection ---------------------------------------------------------------

function collectionPage(shell, sec, p) {
  const url = `${SITE}${sec.path}${p.slug}/`;
  const image = p.hero_image_url || null;
  const article = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: p.title,
    description: p.meta_description,
    abstract: p.short_answer,
    image: image || undefined,
    datePublished: p.created_at,
    dateModified: p.updated_at || p.created_at,
    url,
    mainEntityOfPage: { '@type': 'WebPage', '@id': url },
    inLanguage: 'en-US',
    keywords: (p.keywords || []).join(', '),
    about: p.about || undefined,
    spatialCoverage: p.place ? { '@type': 'City', name: p.place } : undefined,
    author: { '@type': 'Organization', '@id': ORG_ID, name: 'WeDeepen', url: SITE },
    publisher: { '@type': 'Organization', '@id': ORG_ID, name: 'WeDeepen', url: SITE },
  };
  const breadcrumb = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: sec.label, item: `${SITE}${sec.path}` },
      { '@type': 'ListItem', position: 2, name: p.title, item: url },
    ],
  };
  const updated = p.updated_at && day(p.updated_at) !== day(p.created_at)
    ? ` &middot; Updated <time datetime="${esc(p.updated_at)}">${esc(prettyDate(p.updated_at))}</time>` : '';

  const body = `  <!-- ============================
       STANDALONE: ${sec.label.toUpperCase()} PAGE (generated by scripts/build-standalone.mjs; edit ${sec.data})
       ============================ -->
  <main>
  <section class="pt-32 md:pt-40 pb-8 px-6">
    <div class="max-w-3xl mx-auto">
      <a href="${sec.path}" class="text-gold text-sm hover:underline inline-flex items-center gap-2 mb-6">&larr; All ${esc(sec.label.toLowerCase())}</a>
      <p class="text-gold text-xs tracking-[0.25em] uppercase font-semibold mb-3">${esc(p.kicker || sec.label)}</p>
      <h1 class="font-heading text-4xl md:text-5xl font-normal leading-[1.1] tracking-tight">${esc(p.title)}</h1>
      <p class="text-white/50 text-sm mt-5">By <a href="/about/" class="text-gold hover:underline">WeDeepen</a> &middot; <time datetime="${esc(p.created_at)}">${esc(prettyDate(p.created_at))}</time>${updated}</p>
      <div class="mt-8 rounded-2xl p-6 border border-gold/30" style="background: rgba(201,162,119,0.06);">
        <p class="text-gold text-xs tracking-[0.2em] uppercase font-semibold mb-2">The short answer</p>
        <p class="text-white/90 leading-relaxed" data-geo="summary">${esc(p.short_answer)}</p>
      </div>
    </div>
  </section>

  <section class="pb-20 md:pb-28 px-4 sm:px-6">
    <div class="max-w-3xl mx-auto bg-white rounded-2xl px-5 py-8 sm:px-10 sm:py-12">
${image ? `      <img src="${esc(image)}" alt="${esc(p.title)}" class="w-full rounded-xl mb-10" loading="eager">\n` : ''}      <article class="prose prose-gray prose-table:my-8 prose-a:text-[#A01B4A] max-w-none">
${hardenLinks(p.content_html)}
      </article>
      <p class="text-gray-500 text-xs mt-10 border-t border-gray-200 pt-6">Prices, schedules, and listings change. The linked pages are the source of truth; WeDeepen is not affiliated with the other organizations named here.</p>
    </div>
  </section>
  </main>`;

  const pageTitle = `${p.title} | WeDeepen`.length <= 60 ? `${p.title} | WeDeepen` : p.title;
  return page(shell, { title: pageTitle, description: p.meta_description, url, image, type: 'article', keywords: (p.keywords || []).join(', ') },
    [article, faqFromHtml(p.content_html), breadcrumb], body);
}

function collectionIndex(shell, sec, pages) {
  const url = `${SITE}${sec.path}`;
  const cards = pages.map((p) => `        <a href="${sec.path}${p.slug}/" class="group block rounded-2xl p-6 bg-white/[0.03] border border-white/10 hover:border-gold/40 transition">
          <p class="text-gold text-xs tracking-[0.2em] uppercase font-semibold mb-2">${esc(p.kicker || sec.label)}</p>
          <h2 class="font-heading text-xl font-semibold leading-snug group-hover:text-gold transition mb-3">${esc(p.title)}</h2>
          <p class="text-white/60 text-sm leading-relaxed">${esc(p.short_answer)}</p>
        </a>`).join('\n');
  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'CollectionPage',
    name: sec.title,
    description: sec.description,
    url,
    publisher: { '@type': 'Organization', '@id': ORG_ID, name: 'WeDeepen', url: SITE },
    mainEntity: {
      '@type': 'ItemList',
      itemListElement: pages.map((p, i) => ({ '@type': 'ListItem', position: i + 1, name: p.title, url: `${SITE}${sec.path}${p.slug}/` })),
    },
  };
  const body = `  <!-- ============================
       STANDALONE: ${sec.label.toUpperCase()} INDEX (generated by scripts/build-standalone.mjs)
       ============================ -->
  <main>
  <section class="pt-32 md:pt-40 pb-12 px-6">
    <div class="max-w-5xl mx-auto">
      <p class="text-gold text-xs tracking-[0.25em] uppercase font-semibold mb-3">${esc(sec.label)}</p>
      <h1 class="font-heading text-4xl md:text-5xl font-normal leading-[1.1] tracking-tight mb-5">${esc(sec.title)}</h1>
      <p class="text-white/60 leading-relaxed max-w-2xl">${esc(sec.description)}</p>
    </div>
  </section>
  <section class="pb-24 md:pb-32 px-6">
    <div class="max-w-5xl mx-auto grid gap-6 sm:grid-cols-2">
${cards}
    </div>
  </section>
  </main>`;
  return page(shell, { title: sec.title, description: sec.description, url, image: null, type: 'website' }, [jsonLd], body);
}

async function buildCollection(sec) {
  const shell = borrowShell(donor, sec.path);
  const pages = ((await readJson(sec.data)).pages || [])
    .map((p) => ({ ...p, slug: safeSlug(p.slug || p.title) }))
    .filter((p) => p.slug && p.title && p.content_html && p.short_answer && p.slug !== 'data')
    .sort((a, b) => String(a.order ?? 999).localeCompare(String(b.order ?? 999), undefined, { numeric: true }));
  const slugs = new Set(pages.map((p) => p.slug));
  const dir = dirOf(sec.path);
  for (const e of await fs.readdir(dir, { withFileTypes: true }).catch(() => [])) {
    if (e.isDirectory() && e.name !== 'data' && !slugs.has(e.name)) {
      await fs.rm(path.join(dir, e.name), { recursive: true });
      console.log(`  removed ${sec.path.slice(1)}${e.name}/`);
    }
  }
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, 'index.html'), collectionIndex(shell, sec, pages), 'utf8');
  for (const p of pages) {
    await fs.mkdir(path.join(dir, p.slug), { recursive: true });
    await fs.writeFile(path.join(dir, p.slug, 'index.html'), collectionPage(shell, sec, p), 'utf8');
  }
  const newest = pages.reduce((m, p) => ((p.updated_at || p.created_at) > m ? (p.updated_at || p.created_at) : m), '');
  console.log(`Wrote ${sec.path} and ${pages.length} page${pages.length === 1 ? '' : 's'}`);
  return [
    { loc: `${SITE}${sec.path}`, lastmod: day(newest), changefreq: 'weekly', priority: '0.7' },
    ...pages.map((p) => ({ loc: `${SITE}${sec.path}${p.slug}/`, lastmod: day(p.updated_at || p.created_at), changefreq: 'monthly', priority: '0.7' })),
  ];
}

