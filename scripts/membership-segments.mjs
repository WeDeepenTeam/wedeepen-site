export function buildSegment(membership, seg) {
  const url = `${BASE}${seg.slug}/`;
  let html = membership;

  // ---- Meta + measurement ----
  html = replaceOnce(html, /<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${url}">`, 'canonical');
  html = replaceOnce(html, /<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${url}">`, 'og:url');
  html = replaceOnce(html, /<title>[^<]*<\/title>/, `<title>${seg.title}</title>`, 'title');
  html = html.replace(/(<meta (?:property="og:title"|name="twitter:title") content=")[^"]*"/g, `$1${seg.title}"`);
  html = html.replace(/(<meta (?:name="description"|property="og:description"|name="twitter:description") content=")[^"]*"/g, `$1${seg.description}"`);
  html = replaceOnce(html, /gtag\('config', 'G-LZ0EY5X593'\);/,
    `gtag('config', 'G-LZ0EY5X593', { content_group: '${seg.group}', page_variant: '${seg.slug}' });`, 'GA4 config');
  html = replaceOnce(html, /content_name: 'WeDeepen Membership'/, `content_name: 'WeDeepen ${seg.group}'`, 'ViewContent name');
  html = replaceOnce(html, /(checkout\/wedeepen-club-membership\?price_id=\d+)"/g, `$1&amp;utm_content=${seg.utm}"`, 'checkout links');
  html = replaceOnce(html, /Edit index\.html instead\. -->/,
    `Edit index.html (and scripts/membership-segments.mjs for this page's copy) instead. -->`, 'generated note');

  html = replaceOnce(html, /<html lang="en">/, '<html lang="en" data-recordings="library">', 'html tag');

  // ---- Hero ----
  html = replaceOnce(html, /<span class="text-white">Get better at love\.<\/span>/, `<span class="text-white">${seg.h1}</span>`, 'hero h1');
  html = replaceOnce(html,
    /Love is a skill\. Most of us were never taught it\. Here, we practice it out loud, with experts who&rsquo;ve spent their careers on it\./,
    seg.sub, 'hero subhead');

  // ---- At a glance closing line ----
  html = replaceOnce(html,
    /Whether you&rsquo;re dating, building something new, or keeping a long love alive, the skills underneath are the same\./,
    seg.glance, 'glance line');

  // ---- The skill section ----
  html = replaceOnce(html, /Love has a much messier learning curve than most things we get good at\./, seg.skillH2, 'skill h2');
  html = replaceOnce(html,
    /We develop skills in work, health, and sport through learning, practice, and feedback\. Love is usually left to experience\./,
    seg.skillP1, 'skill p1');
  html = replaceOnce(html,
    /WeDeepen gives you a place to build the skill of love deliberately, including learning to tell the difference between:/,
    seg.skillP2, 'skill p2');
  html = replaceOnce(html, /(<div class="home-ledger">\n)[\s\S]*?(\n[ \t]*<\/div>)/, (m, a, b) => `${a}${ledger(seg.ledger)}${b}`, 'ledger');

  // ---- What you build ----
  html = replaceOnce(html,
    /Build the skills that make love <span class="italic" style="color:#C9A277;">easier<\/span> to navigate\./,
    seg.buildH2, 'build h2');
  html = replaceOnce(html,
    /(<section data-m2="build"[\s\S]*?<ul class="border-t border-white\/10">\n)[\s\S]*?(\n[ \t]*<\/ul>)/,
    (m, a, b) => `${a}${buildList(seg.build)}${b}`, 'build list');

  // ---- Testimonial videos, right before what's included ----
  html = replaceOnce(html, /([ \t]*<!-- =+\s*SECTION 2b: WHAT THE MEMBERSHIP INCLUDES)/, `${videoSection(seg)}$1`, 'video section');

  // ---- Recordings: the growing library is open from day one ----
  html = replaceOnce(html, /Recordings of every Love Mastermind from the time you join forward\./,
    'The growing library of Love Mastermind recordings, open from your first day.', 'recordings bullet');
  html = replaceOnce(html, /catch Love Mastermind recordings from the time you join forward\./,
    'catch up in the Love Mastermind recording library.', 'FAQ time');
  html = replaceOnce(html, /Every Love Mastermind is recorded from the time you join forward, so you can catch it later from anywhere\./,
    'Love Masterminds are recorded, and the whole recording library opens on your first day, so you can catch up from anywhere.', 'FAQ missed session');
  html = replaceOnce(html, /Recordings of Love Masterminds held after you join/,
    'The growing Love Mastermind recording library, from day one', 'final card recordings');

  // ---- Text testimonials for this audience ----
  for (const name of seg.removeCards) html = removeCard(html, name);
  if (seg.testimonialsHeading) {
    html = replaceOnce(html, />What Members Say<\/h2>/, `>${seg.testimonialsHeading}</h2>`, 'testimonials heading');
  }
  if (seg.priceQuote) {
    html = replaceOnce(html,
      /(<p class="font-heading italic text-white\/85 text-lg md:text-xl leading-relaxed">&ldquo;)[^<]*(&rdquo;<\/p>\n[ \t]*<p class="text-white\/50 text-xs uppercase tracking-\[0\.2em\] mt-3">)Bo L\., Member/,
      `$1${seg.priceQuote.text}$2${seg.priceQuote.who}`, 'price-block quote');
  }
  return html;
}
