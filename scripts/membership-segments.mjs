/**
 * membership-segments.mjs — audience landing pages built from /membership/.
 *
 * Each segment page is the full membership page (so it stays in sync with the
 * homepage) with copy for one audience swapped in:
 *   /membership/dating-again/  dating again after a long relationship or marriage
 *   /membership/together/      a long relationship or marriage, keeping it alive
 *
 * What changes per page: title/meta, measurement (GA4 content group, Meta
 * ViewContent name, utm_content on checkout links), hero, the "skill" and
 * "build" sections, a testimonial video row, which text testimonials show,
 * and the recordings wording (the growing Love Mastermind library is open from
 * day one). Everything else is the membership page as-is.
 *
 * Called by build-membership.mjs. Never edit the generated pages by hand.
 */

const BASE = 'https://wedeepen.com/membership/';

function replaceOnce(html, pattern, replacement, label) {
  const next = html.replace(pattern, replacement);
  if (next === html) throw new Error(`membership-segments: couldn't find ${label}`);
  return next;
}

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// One text testimonial card in the "What Members Say" grid, found by name.
function removeCard(html, name) {
  const re = new RegExp(
    `\\n[ \\t]*<div class="bg-white rounded-xl p-6 shadow-sm">(?:(?!<div class="bg-white rounded-xl)[\\s\\S])*?${esc(name)}[\\s\\S]*?\\n        </div>\\n`);
  return replaceOnce(html, re, '\n', `testimonial card ${name}`);
}

function buildList(items) {
  return items.map((t, i) => `            <li class="flex gap-6 py-5 border-b border-white/10">
              <span class="text-gold text-xs tracking-[0.2em] font-semibold pt-1.5 shrink-0">${String(i + 1).padStart(2, '0')}</span>
              <span class="text-white/80 text-lg leading-relaxed">${t}</span>
            </li>`).join('\n');
}

function ledger(pairs) {
  return pairs.map(([a, b]) => `        <p class="hl-term font-heading text-[1.7rem] md:text-[2.1rem] leading-tight">${a}</p>
        <p class="hl-vs text-charcoal/30 text-[0.65rem] uppercase tracking-[0.26em]">versus</p>
        <p class="hl-counter font-heading italic text-[1.7rem] md:text-[2.1rem] leading-tight" style="color:#A01B4A;">${b}</p>`).join('\n');
}

// Testimonial video row. Files live in /videos/testimonials/<file>.mp4 (+ .jpg
// poster). A tile whose video can't load hides itself; if none load, the whole
// section hides, so the page never shows an empty player.
function videoSection(seg) {
  const tiles = seg.videos.map((v) => `        <figure class="wd-vt rounded-md overflow-hidden shrink-0 w-[82%] sm:w-auto snap-center" style="background:#000;border:1px solid rgba(255,255,255,0.08);">
          <video class="w-full block aspect-video object-cover" controls playsinline preload="metadata" poster="/videos/testimonials/${v.file}.jpg">
            <source src="/videos/testimonials/${v.file}.mp4#t=0.5" type="video/mp4">
          </video>
          <figcaption class="px-4 py-3 text-white/70 text-sm">${v.name}</figcaption>
        </figure>`).join('\n');
  return `  <!-- ============================
       SECTION 2a+: IN THEIR WORDS — testimonial videos for this audience
       (generated by scripts/membership-segments.mjs)
       ============================ -->
  <section id="in-their-words" data-m2="videos" class="bg-ink pb-24 md:pb-32 px-6">
    <div class="max-w-site mx-auto reveal">
      <div class="text-center mb-12">
        <h2 class="font-heading text-3xl md:text-4xl lg:text-5xl font-normal leading-tight mb-4" style="text-wrap: balance;">${seg.videoHeading}</h2>
        <p class="text-white/60 text-lg max-w-2xl mx-auto">${seg.videoSub}</p>
      </div>
      <div class="flex sm:grid sm:grid-cols-2 lg:grid-cols-3 gap-4 sm:gap-5 overflow-x-auto sm:overflow-visible snap-x snap-mandatory -mx-6 px-6 sm:mx-0 sm:px-0 pb-2">
${tiles}
      </div>
      <p class="sm:hidden text-center text-white/40 text-xs uppercase tracking-[0.25em] mt-4">Swipe &rarr;</p>
      <div class="text-center mt-10 sm:mt-12">
        <a data-cta="videos" href="https://circle.wedeepen.com/checkout/wedeepen-club-membership?price_id=368281&amp;utm_content=${seg.utm}" class="btn-rose text-base">Start my 14 free days</a>
      </div>
    </div>
  </section>
  <script>
  (function(){
    var sec=document.getElementById('in-their-words'); if(!sec) return;
    var tiles=[].slice.call(sec.querySelectorAll('.wd-vt'));
    function check(){ if(!tiles.some(function(t){return t.style.display!=='none';})) sec.style.display='none'; }
    tiles.forEach(function(t){
      var v=t.querySelector('video'), s=t.querySelector('source');
      function gone(){ t.style.display='none'; check(); }
      s.addEventListener('error', gone); v.addEventListener('error', gone);
      v.addEventListener('play', function(){ tiles.forEach(function(o){ var ov=o.querySelector('video'); if(ov!==v) ov.pause(); });
        if(window.gtag) gtag('event','testimonial_play',{video: t.querySelector('figcaption').textContent}); });
    });
  })();
  </script>


`;
}

